// Measures how big every text motion of every おまかせ mood really draws a line at rest — width and height in multiples of the font size — in wide and tall
// for lines of 5 to 35 characters at the biggest size the plan would give such a line, and writes app/studio/omakase-extents.js.
// placeLine() (app/studio/omakase.js) uses it to keep a moved / tilted line inside the picture.
// Run:  node tools/omakase_extents.mjs        (needs Chrome and playwright-core; see UNFOLD_PLAYWRIGHT_PATH / UNFOLD_CHROMIUM as in tools/test/studio/browser-helper.mjs)
import {pathToFileURL} from 'node:url';
import {writeFile} from 'node:fs/promises';
import {startStaticServer} from './lib/static-server.mjs';
const fallback='/Volumes/ORICO/UNFOLD/.worktrees/method-workshop/tools/image-code-build/.test-deps/node_modules/playwright-core/index.mjs';
const {chromium}=await import(pathToFileURL(process.env.UNFOLD_PLAYWRIGHT_PATH||fallback));
const server=await startStaticServer();
const browser=await chromium.launch({executablePath:process.env.UNFOLD_CHROMIUM||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
try{
 const page=await browser.newPage();page.on('pageerror',e=>console.log('pageerror',e.message));
 await page.goto(server.url+'/workshop.html');
 const rows=await page.evaluate(async()=>{
  const {createCodeMotionRuntime}=await import('./code-motion-runtime.js'),{getCodeMotionFont}=await import('./lyric-fonts.js'),{MOODS,fitCap,motionOf}=await import('./studio/omakase.js');
  const fontBytes=await getCodeMotionFont('gothic');
  const keys=[...new Set(MOODS.flatMap(m=>m.text))];
  const LINES={5:'私は元気です',10:'かたちをほどいて自由に。',16:'君と見た夏の終わりの空は今でも',24:'君と見た夏の終わりの空は今でも覚えているよずっと',35:'君と見た夏の終わりの空は今でも覚えているよずっとずっと忘れない大切な記憶'};
  const out=[];
  for(const key of keys){const src=motionOf(key).source;
   for(const [W,H] of [[960,540],[540,960]])for(const n of [5,10,16,24,35]){
    const text=LINES[n].slice(0,n),chars=[...text].length,fontScale=Math.min(.24,fitCap(chars)),fs=fontScale*Math.min(W,H);
    const rt=createCodeMotionRuntime();let x0=1e9,y0=1e9,x1=-1,y1=-1,err=null;
    try{await rt.prepare({source:src,text,runs:[{id:'a',text}],width:W,height:H,fontSize:fs,color:'#ffffff',accent:'#ff6b81',font:'gothic',seed:7,duration:3,bpm:120,fontBytes:fontBytes.slice(0)});
     for(const t of [1.3,1.7,2.1]){const b=await rt.render(t);const c=new OffscreenCanvas(W,H),x=c.getContext('2d',{willReadFrequently:true});x.drawImage(b,0,0);b.close();const d=x.getImageData(0,0,W,H).data;
      for(let y=0;y<H;y++)for(let xx=0;xx<W;xx++)if(d[(y*W+xx)*4+3]>24){if(xx<x0)x0=xx;if(xx>x1)x1=xx;if(y<y0)y0=y;if(y>y1)y1=y;}}
    }catch(e){err=String(e.message||e).slice(0,100)}finally{rt.dispose()}
    out.push({key,err,view:W>H?'wide':'tall',n:chars,w:x1<0?0:(x1-x0+1)/fs,h:y1<0?0:(y1-y0+1)/fs});
   }}
  return out;
 });
 const byKey={};
 for(const r of rows){if(r.err){console.log('FAILED',r.key,r.err);continue;}((byKey[r.key]??={})[r.view]??=[]).push([r.n,r.w,r.h]);}
 // a 5 % safety margin, rounded up to 0.05 (multiples of the font size)
 const up=v=>Math.ceil(v*1.05*20)/20;
 const fmt=list=>'['+list.map(([n,w,h])=>`[${n},${up(w).toFixed(2)},${up(h).toFixed(2)}]`).join(',')+']';
 const lines=Object.keys(byKey).sort().map(k=>`  '${k}':{wide:${fmt(byKey[k].wide||[])},tall:${fmt(byKey[k].tall||[])}},`);
 await writeFile(new URL('../app/studio/omakase-extents.js',import.meta.url),`// Generated by tools/omakase_extents.mjs — do not edit by hand. For every text motion of the おまかせ moods: how wide and how tall (in multiples of the font size)\n// its line really is at rest, for lines of 5 to 35 characters, in the wide and the tall picture, at the biggest size the plan gives such a line.\n// [characters, width, height]. placeLine() reads between these so that a moved or tilted line stays inside the picture.\nexport const EXTENTS={\n${lines.join('\n')}\n};\n`);
 console.log('wrote',lines.length,'motions');
}finally{await browser.close();await server.close();}
